  static String tr(String? languageCode, String key) {
    final dict = _dict[languageCode] ?? _dict['en']!;
    return dict[key] ?? _dict['en']![key] ?? key;
  }

  static String fill(String template, Map<String, String> values) {
    var out = template;
    values.forEach((k, v) => out = out.replaceAll('{$k}', v));
    return out;
  }
}

extension L10nX on BuildContext {
  String tr(String key, [Map<String, String>? values]) {
    final appState = Provider.of<AppState>(this, listen: false);
    var s = L10n.tr(appState.localeCode, key);
    if (values != null) s = L10n.fill(s, values);
    return s;
  }
}
